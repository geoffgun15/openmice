"""Install as boot.py on both devices, then power-cycle."""
import usb_cdc
import usb_hid
import supervisor

# 5 buttons, signed 16-bit X/Y, signed 8-bit wheel: 6-byte report, ID 2.
# CircuitPython's standard keyboard uses ID 1; IDs share one HID interface.
MOUSE_DESCRIPTOR = bytes((
    0x05,0x01,0x09,0x02,0xA1,0x01,0x85,0x02,0x09,0x01,0xA1,0x00,
    0x05,0x09,0x19,0x01,0x29,0x05,0x15,0x00,0x25,0x01,0x95,0x05,0x75,0x01,0x81,0x02,
    0x95,0x01,0x75,0x03,0x81,0x03,
    0x05,0x01,0x09,0x30,0x09,0x31,0x16,0x00,0x80,0x26,0xFF,0x7F,
    0x75,0x10,0x95,0x02,0x81,0x06,
    0x09,0x38,0x15,0x81,0x25,0x7F,0x75,0x08,0x95,0x01,0x81,0x06,0xC0,0xC0))
mouse = usb_hid.Device(report_descriptor=MOUSE_DESCRIPTOR, usage_page=1, usage=2,
                       report_ids=(2,), in_report_lengths=(6,), out_report_lengths=(0,))
usb_hid.enable((mouse,usb_hid.Device.KEYBOARD))
usb_cdc.enable(console=False,data=True)
supervisor.disable_autoreload()
