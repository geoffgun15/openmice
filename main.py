def read_motion():
    spi_write(0x16, 0x00)
    time.sleep(0.002)
    cs.value = False
    while not spi.try_lock():
        pass
    spi.configure(baudrate=1000000, phase=1, polarity=1)
    spi.write(bytes([0x16 & 0x7F]))
    data = bytearray(6)
    spi.readinto(data)
    spi.unlock()
    cs.value = True
    return data

