import board
import digitalio
import busio
import time

# Setup SPI and CS
cs = digitalio.DigitalInOut(board.P0_24)  # Choose any free GPIO for CS
cs.direction = digitalio.Direction.OUTPUT
cs.value = True

spi = busio.SPI(clock=board.SCK, MOSI=board.MOSI, MISO=board.MISO)

def spi_write(register, value):
    cs.value = False
    while not spi.try_lock():
        pass
    spi.configure(baudrate=1000000, phase=1, polarity=1)
    spi.write(bytes([register | 0x80, value]))
    spi.unlock()
    cs.value = True
    time.sleep(0.001)

def spi_read(register):
    cs.value = False
    while not spi.try_lock():
        pass
    spi.configure(baudrate=1000000, phase=1, polarity=1)
    spi.write(bytes([register & 0x7F]))
    result = bytearray(1)
    spi.readinto(result)
    spi.unlock()
    cs.value = True
    time.sleep(0.001)
    return result[0]

